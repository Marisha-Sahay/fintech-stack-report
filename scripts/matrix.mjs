#!/usr/bin/env node
// Collects the "## Matrix row" table from every research/companies/*.md note
// and writes research/matrix-by-dimension.md: one table per dimension, one row per company.
// This is a working file for synthesis; the report's own matrix (report/03) is written by hand
// with short cells and citations.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'research/companies');
const files = readdirSync(dir).filter((f) => f.endsWith('.md') && !f.startsWith('_')).sort();

const dims = new Map(); // dimension -> [{company, value, evidence, key}]
const missing = [];

for (const f of files) {
  const md = readFileSync(join(dir, f), 'utf8');
  const company = (md.match(/^# (.+)$/m) || [null, f])[1].trim();
  const start = md.search(/^## Matrix row\s*$/m);
  if (start < 0) { missing.push(f); continue; }
  const block = md.slice(start).split('\n').slice(1);
  for (const line of block) {
    const t = line.trim();
    if (t.startsWith('## ')) break;
    if (!t.startsWith('|')) continue;
    const [dim, value, evidence, key] = t.replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
    if (!dim || dim === 'Dimension' || /^-+$/.test(dim)) continue;
    if (!dims.has(dim)) dims.set(dim, []);
    dims.get(dim).push({ company, value: value || '', evidence: evidence || '', key: key || '' });
  }
}

let out = `# Matrix by dimension (generated)\n\nGenerated by \`node scripts/matrix.mjs\` from ${files.length} company notes. Do not edit by hand.\n`;
if (missing.length) out += `\nNotes without a Matrix row section: ${missing.join(', ')}\n`;
for (const [dim, rows] of dims) {
  out += `\n## ${dim}\n\n| Company | Value | Evidence | Key |\n|---|---|---|---|\n`;
  for (const r of rows) out += `| ${r.company} | ${r.value} | ${r.evidence} | ${r.key} |\n`;
}
writeFileSync(join(root, 'research/matrix-by-dimension.md'), out);
console.log(`companies: ${files.length}  dimensions: ${dims.size}${missing.length ? `  missing matrix: ${missing.join(', ')}` : ''}`);
